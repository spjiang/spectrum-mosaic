const BA_STAGE_ROLE: Record<string, string> = {
  "1": "这一阶段只修正焦距和主点，先把照片位姿和主距稳住。",
  "2": "在上一阶段的结果上再修正径向畸变，把重投影误差收紧。",
  "3": "再修正高阶畸变、切向畸变和仿射项，得到最终的相机标定。",
};

export function stepHelp(name: string): StepHelp {
  const known = HELP[name];
  if (known) return known;
  const stage = /^平差阶段(\d+)$/.exec(name);
  if (stage) {
    return {
      does: "把照片的位置朝向、地面点和相机内参放在一起整体修正，让同一个地面点投回每张照片都落到原来的像点上。",
      role: BA_STAGE_ROLE[stage[1]] || "继续收紧重投影误差，并剔掉偏差过大的观测。",
    };
  }
  if (name.startsWith("正射 ")) {
    const band = name.slice("正射 ".length);
    return {
      does: `把 ${band} 波段的照片按地形投到地图格网上，并写成这个波段的正射影像。`,
      role: "每个波段各出一张正射，后面的质量报告和交付用的就是这些图。",
    };
  }
  return {
    does: "记录这一步实际做完的事和统计。",
    role: "用来核对这一步有没有跑完、花了多久。",
  };
}
